// Packs lib/lifecycle/templates/*.html|txt into lib/lifecycle/templates.data.mjs, so the Netlify bundle carries them.
// Edit the .html/.txt files, then run: npm run build:lifecycle-templates
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

export async function buildLifecycleTemplates(projectRoot = root) {
  const dir = join(projectRoot, 'lib/lifecycle/templates');
  const names = (await readdir(dir)).filter(name => /\.(html|txt)$/.test(name)).sort();
  const data = {};
  for (const name of names) data[name] = await readFile(join(dir, name), 'utf8');
  const content = `// Generated by scripts/build-lifecycle-templates.mjs from lib/lifecycle/templates. Do not edit by hand.\nexport const TEMPLATES = ${JSON.stringify(data, null, 1)};\n`;
  await writeFile(join(projectRoot, 'lib/lifecycle/templates.data.mjs'), content);
  return names;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const names = await buildLifecycleTemplates();
  console.log(`Packed ${names.length} lifecycle templates.`);
}
