import { readdir, readFile, mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parse } from 'acorn';

const root = fileURLToPath(new URL('../', import.meta.url));

// Keep the existing handlers in their original paths. Only these generated
// entry points are uploaded, so every function uses the modern runtime.
export async function buildFunctions(projectRoot = root) {
  const sourceDir = join(projectRoot, 'netlify/functions');
  const outputDir = join(projectRoot, 'netlify/runtime-functions');
  const entries = (await readdir(sourceDir, { withFileTypes: true }))
    .filter(entry => entry.isFile() && /\.(?:mjs|cjs|js)$/.test(entry.name))
    .sort((a, b) => a.name.localeCompare(b.name));
  const generated = [];
  for (const entry of entries) {
    const source = await readFile(join(sourceDir, entry.name), 'utf8');
    const ast = parse(source, { ecmaVersion: 'latest', sourceType: 'module', allowReturnOutsideFunction: true });
    const modern = ast.body.some(node => node.type === 'ExportDefaultDeclaration');
    let config = '';
    for (const node of ast.body) {
      const declaration = node.type === 'ExportNamedDeclaration' ? node.declaration : node;
      for (const variable of declaration?.declarations || []) {
        if (variable.id.name === 'config' && variable.init?.type === 'ObjectExpression') {
          config = source.slice(variable.init.start, variable.init.end);
        }
      }
      const assignment = node.type === 'ExpressionStatement' ? node.expression : null;
      if (assignment?.type === 'AssignmentExpression' && assignment.left.type === 'MemberExpression' && assignment.left.object.name === 'exports') {
        if (assignment.left.property.name === 'config') config = source.slice(assignment.right.start, assignment.right.end);
        if (assignment.left.property.name === 'schedule') config = `{ schedule: ${source.slice(assignment.right.start, assignment.right.end)} }`;
      }
    }
    const name = entry.name.replace(/\.(?:mjs|cjs|js)$/, '');
    if (!config && name.endsWith('-background')) config = '{ background: true }';
    const sourceImport = JSON.stringify(`../functions/${entry.name}`);
    const body = modern
      ? `import handler from ${sourceImport};\nexport default handler;\n`
      : `import * as original from ${sourceImport};\nimport { withLegacyHandler } from '../../lib/netlify/legacy-handler.mjs';\nexport default withLegacyHandler(original.handler || original.default?.handler);\n`;
    generated.push({ name, modern, content: `// Generated by scripts/build-netlify-functions.mjs.\n${body}${config ? `export const config = ${config};\n` : ''}` });
  }
  // Parse everything before replacing generated output; never copy secrets.
  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });
  for (const entry of generated) await writeFile(join(outputDir, `${entry.name}.mjs`), entry.content);
  return generated;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const entries = await buildFunctions();
  console.log(`Prepared ${entries.length} modern Netlify function entry points (${entries.filter(entry => !entry.modern).length} adapted handlers).`);
}
